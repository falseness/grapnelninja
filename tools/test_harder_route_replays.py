"""Recorded production-input replays of single v12 transfers, not a from-spawn climb.

The P24/P27/P31/P35 upper-combination replays and the whole-route coverage check
were retired by TASK-831: their recorded aims stopped reaching the targets after
the intended camera changes c2a6743 TASK-688 (scale 0.375 -> 0.25) and 271eb97
TASK-692 (camera centered on the ninja)."""
from contextlib import ExitStack
import json
import os
from pathlib import Path
import unittest
from browser_test_support import start_browser_test, wait_for_boot_run

ROOT = Path(__file__).resolve().parent.parent
TOOLS = ROOT / 'tools'
# The v12 retune candidate these pins were written for (49cf58e); its level.json is
# byte-equal to 49cf58e:leveldata.js. artifacts/levels holds the shipped layout,
# regenerated by every later ship (v13 ad15d03 TASK-677 .. v22 4da5278 TASK-781).
DIR = Path(os.environ.get('HARDER_LEVEL_DIR', ROOT / 'artifacts/levels/harder-right/long400'))

class HarderReplayTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        path = DIR / 'extended-mountain.level.json'
        if not path.exists(): path = DIR / 'level.json'
        cls.level = json.loads(path.read_text())
        cls.local = json.loads((TOOLS / 'fixtures/harder-transfer-inputs.json').read_text())
        cls.stack = ExitStack(); cls.addClassCleanup(cls.stack.close)
        url, browser = start_browser_test(ROOT, cls.stack.callback)
        cls.pages = {}
        for script in ('probe_level_routes',):
            page = browser.new_page(); page.goto(url); wait_for_boot_run(page)
            page.add_script_tag(path=str(TOOLS / (script + '.js')))
            cls.pages[script] = page

    def test_other_transfers(self):
        page = self.pages['probe_level_routes']
        for policy in self.local:
            with self.subTest(source=policy['source']):
                result=page.evaluate('o=>ROUTE_PROBE.run(o)',dict(policy,level=self.level))
                self.assertIsNotNone(result['hit'])
                self.assertEqual(result['hit']['id'],policy['target']+'-body0')

if __name__=='__main__':unittest.main()
